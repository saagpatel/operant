#!/usr/bin/env node
// Bake the signed discovery manifest into src/well-known.generated.ts so the Worker
// serves the EXACT bytes that were signed (operant.saagarpatel.dev has no static host
// — the Worker is the only origin). Mirrors scripts/build-corpus.mjs.
//
// Reads .well-known/{mcp.json, mcp.json.sig, mcp-ed25519.pub} and embeds each as a
// raw string constant. Because the signature is over the manifest's raw bytes, the
// Worker must serve those exact bytes — embedding the file content verbatim guarantees
// it. Re-run `sign` then this script after any manifest change.
//
//   node scripts/build-wellknown.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const PKG_DIR = resolve(new URL("..", import.meta.url).pathname);
const read = (rel) => readFileSync(resolve(PKG_DIR, rel), "utf8");

const manifest = read(".well-known/mcp.json");
const signature = read(".well-known/mcp.json.sig");
const publicKey = read(".well-known/mcp-ed25519.pub");

// JSON.stringify produces a valid, fully-escaped double-quoted TS string literal,
// so the embedded bytes round-trip exactly (newlines, quotes, and all).
const out =
	"// AUTO-GENERATED by scripts/build-wellknown.mjs — do not edit by hand.\n" +
	"// The signed discovery manifest, served verbatim by the Worker at\n" +
	"// /.well-known/mcp.json (+ .sig and the Ed25519 public key).\n\n" +
	`export const MANIFEST_JSON = ${JSON.stringify(manifest)};\n\n` +
	`export const MANIFEST_SIG = ${JSON.stringify(signature)};\n\n` +
	`export const MANIFEST_PUBKEY = ${JSON.stringify(publicKey)};\n`;

writeFileSync(resolve(PKG_DIR, "src/well-known.generated.ts"), out);

console.log(
	`baked well-known: manifest ${manifest.length}B, sig ${signature.trim().length}B, ` +
		"pubkey embedded -> src/well-known.generated.ts",
);
